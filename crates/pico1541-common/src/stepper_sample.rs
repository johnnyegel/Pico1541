#[inline]
fn volume_gain(volume: SoundVolume, top: u16) -> i32 {
    match volume {
        SoundVolume::Off => 0,
        SoundVolume::Low => (top as i32) / 120,
        SoundVolume::Medium => (top as i32) / 50,
        SoundVolume::High => (top as i32) / 30,
    }
}

/// Converts a signed 8-bit PCM sample to a 16-bit PWM counter duty value,
/// centered around `top / 2` (1.65V DC), modulated by volume gain.
///
/// Used when the spindle motor is active and the ultrasonic carrier is already running.
#[inline]
pub fn stepper_sample_to_pwm_duty(sample: i8, top: u16, volume: SoundVolume) -> u16 {
    if volume == SoundVolume::Off {
        return 0;
    }
    let center = (top / 2) as i32;
    let gain = volume_gain(volume, top);
    let duty = center + (sample as i32 * gain);
    duty.clamp(0, top as i32) as u16
}

/// Converts a signed 8-bit PCM sample to a 16-bit PWM counter duty value with
/// a smooth 1.1 ms sub-audible DC ramp-in and ramp-out to eliminate capacitive switching clicks.
///
/// Used when the spindle motor is stopped and the audio starts/ends at 0V DC.
#[inline]
pub fn stepper_sample_to_pwm_duty_stopped(
    sample: i8,
    top: u16,
    volume: SoundVolume,
    index: usize,
    total_len: usize,
) -> u16 {
    if volume == SoundVolume::Off {
        return 0;
    }
    let full_center = (top / 2) as u32;
    let full_gain = volume_gain(volume, top);

    let scale = if index < STEPPER_DC_RAMP_SAMPLES {
        ((index as u32) * 256 / STEPPER_DC_RAMP_SAMPLES as u32) as i32
    } else if index + STEPPER_DC_RAMP_SAMPLES >= total_len {
        let remaining = total_len.saturating_sub(index + 1) as u32;
        ((remaining * 256) / STEPPER_DC_RAMP_SAMPLES as u32) as i32
    } else {
        256
    };

    let center = ((full_center as i32 * scale) / 256) as i32;
    let gain = (full_gain * scale) / 256;
    let duty = center + (sample as i32 * gain);
    duty.clamp(0, top as i32) as u16
}

/// Combines a signed 8-bit motor hum sample and a signed 8-bit stepper/bump sample
/// into a single 16-bit PWM counter duty value, scaled according to the envelope progress.
#[inline]
pub fn mixed_sample_to_pwm_duty_faded(
    motor_sample: i8,
    step_sample: i8,
    top: u16,
    volume: SoundVolume,
    step: u8,
    max_steps: u8,
) -> u16 {
    if volume == SoundVolume::Off || step == 0 || max_steps == 0 {
        return 0;
    }
    let clamped_step = step.min(max_steps) as u32;
    let max_steps_u32 = max_steps as u32;

    let full_center = (top / 2) as u32;
    let center = ((full_center * clamped_step) / max_steps_u32) as i32;

    let full_motor_gain = crate::motor_sample::volume_gain(volume, top);
    let full_step_gain = volume_gain(volume, top);


    let motor_gain = (full_motor_gain * clamped_step as i32) / (max_steps_u32 as i32);
    let step_gain = (full_step_gain * clamped_step as i32) / (max_steps_u32 as i32);

    let ac = (motor_sample as i32 * motor_gain) + (step_sample as i32 * step_gain);
    let duty = center + ac;
    duty.clamp(0, top as i32) as u16
}

